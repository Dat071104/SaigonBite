"""List what a UI refinement must keep: element ids, form field names, data-* hooks, routes and the texts that
tests assert. Writes docs/part2/ui/_before/must_survive.md.  Author: 722I0004 · AI-assisted (Claude Sonnet 5.5)"""
import ast
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3].parent
T = REPO / "saigonbite/presentation/templates"
ids, names, data = {}, {}, {}
for f in sorted(T.rglob("*.html")):
    s = f.read_text(encoding="utf-8")
    rel = f.relative_to(T).as_posix()
    ids[rel] = sorted(set(re.findall(r'\bid="([\w-]+)"', s)) | set(re.findall(r"\bid='([\w-]+)'", s)))
    names[rel] = sorted(set(re.findall(r'\bname="([\w{}.\' ~-]+)"', s)))
    data[rel] = sorted(set(re.findall(r"\b(data-[a-z-]+)", s)))
literals = set()
for f in (REPO / "tests").glob("test_*.py"):
    try:
        tree = ast.parse(f.read_text(encoding="utf-8"))
    except SyntaxError:
        continue
    for node in ast.walk(tree):
        if isinstance(node, ast.Assert) and isinstance(node.test, ast.Compare):
            for op, cmp in zip(node.test.ops, [node.test.left] + node.test.comparators):
                pass
            if isinstance(node.test.ops[0], (ast.In, ast.NotIn)) and isinstance(node.test.left, ast.Constant) \
                    and isinstance(node.test.left.value, str) and len(node.test.left.value) > 3:
                literals.add(node.test.left.value)
lines = ["# What a UI refinement must keep", "", "Author: 722I0004 · AI-assisted (Claude Sonnet 5.5)", "",
         "Generated by `_kit/must_survive.py` at the entry commit of the refinement work. Rule: no route, no form field name, "
         "no element id, no `data-*` hook and none of the asserted texts below changes; the full suite runs after every "
         "refinement commit.", "", "## Routes", "",
         "Unchanged. The 41-row SSD map (`Part2/notes/P4_B02/actual_route_controller_SSD_map.csv`) and "
         "`docs/part2/implementation/p4_route_inventory.json` stay valid; refinements touch templates, `style.css` and `app.js` only.", "",
         "## Hooks per template", "", "| Template | ids | form field names | data-* |", "|---|---|---|---|"]
for rel in ids:
    if ids[rel] or names[rel] or data[rel]:
        lines.append(f"| {rel} | {', '.join(ids[rel])} | {', '.join(names[rel])} | {', '.join(data[rel])} |")
lines += ["", f"## Texts asserted by tests (`assert '<text>' in page`), {len(literals)} literals", ""]
lines += [f"- `{x}`" for x in sorted(literals)]
out = REPO / "docs/part2/ui/_before/must_survive.md"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(ids), "templates;", len(literals), "asserted literals")
