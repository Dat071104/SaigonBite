"""Write docs/part2/ui/UC-0x/trace.md.

Author: 722I0004 · AI-assisted (Claude Sonnet 5.5)

  make_trace.py UC-01 [UC-05 ...]

Automatic columns (cannot drift): the SSD operation and occurrence, the screens that serve it (screens.csv), the HTTP
route and the controller method (SSD map, SHA-256 7fcb455e...), the guards and PC/MG anchors (docs/part2/ssd_operations.csv).
Each controller call is also checked against the view source: the method name must appear as a call in the view
module named in the map, otherwise the row says CHECK FAILED.
Hand-written columns come from UC-0x/trace_notes.csv (occurrence, control, inputs_validation, displayed_result).
"Mockup vs implemented" comes from UC-0x/mockup_vs_implemented.md; the artifact dates are the creation dates of the files.
"""
import csv
import hashlib
import os
import re
import sys
from datetime import datetime
from pathlib import Path

UI = Path(__file__).resolve().parents[1]
REPO = UI.parents[2]
MAP = Path(r"D:\RAD\FINAL\Part2\notes\P4_B02\actual_route_controller_SSD_map.csv")
assert hashlib.sha256(MAP.read_bytes()).hexdigest() == "7fcb455ee23df6eebd23663534a177dc5e5c3a54de88503a5552134f4cd22fed"
AUTHOR = "722I0004 · AI-assisted (Claude Sonnet 5.5)"


def rows(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def created(path: Path) -> str:
    return datetime.fromtimestamp(os.stat(path).st_ctime).strftime("%d/%m/%Y")


def view_check(r) -> str:
    src = Path(r["source"])
    method = r["controller_method"].split(".")[-1]
    text = src.read_text(encoding="utf-8") if src.exists() else ""
    # the view calls the controller either directly (_controller().m(...)) or through a local helper variable
    return "yes" if re.search(rf"\.{re.escape(method)}\(", text) else "CHECK FAILED"


def build(uc: str):
    smap = [r for r in rows(MAP) if r["UC"] == uc]
    ops = {r["op_id"]: r for r in rows(REPO / "docs/part2/ssd_operations.csv")}
    screens = rows(UI / "screens.csv")
    notes = {r["occurrence"]: r for r in rows(UI / uc / "trace_notes.csv")}
    out = [f"# {uc} trace: SSD operation to screen, control, validation, result and controller method", "",
           f"Author: {AUTHOR}. Generated by `_kit/make_trace.py` on {datetime.now().strftime('%d/%m/%Y')} from the SSD map, "
           "`ssd_operations.csv`, `screens.csv` and `trace_notes.csv`; the controller calls were checked against the view code.", "",
           "| SSD op (occurrence) | Screen / control | Inputs and validation (rules) | Displayed result | Route → controller method | In view code |",
           "|---|---|---|---|---|---|"]
    failed = 0
    for r in smap:
        occ = r["SSD_identity"].rsplit("#", 1)[1]
        n = notes[occ]
        serving = [s["screen_id"] for s in screens if f"{uc}#{occ}" in s["occurrences"].split()]
        op = ops[r["op_id"]]
        ok = view_check(r)
        failed += ok != "yes"
        parts = [f"{k} {op[col].strip()}" for k, col in (("guards", "guards (BR)"), ("anchors", "PC/MG")) if op[col].strip()]
        guards = f" [{'; '.join(parts)}]" if parts else ""
        out.append(f"| {r['op_id']} {r['operation']} ({occ}) | {', '.join(serving)}: {n['control']} | {n['inputs_validation']}{guards} | "
                   f"{n['displayed_result']} | {r['actual_methods_routes']} → `{r['controller_method']}` | {ok} |")
    out += ["", f"Rows: {len(smap)} SSD occurrences; controller calls found in the view code: {len(smap) - failed} of {len(smap)}.", ""]
    extra = UI / uc / "mockup_vs_implemented.md"
    out += ["## Mockup vs implemented", ""]
    out.append(extra.read_text(encoding="utf-8").strip() if extra.exists() else "NOT WRITTEN YET")
    out += ["", "## Artifacts and their real creation dates", "",
            "The draft screens were built first (I1 to P4). The wireframes, mockups and refinements below are **UI design refinement "
            "after the draft build**; the dates are file creation dates on this machine.", "",
            "| Artifact | Kind | Created |", "|---|---|---|"]
    for kind, label in (("sketch", "sketch (owner)"), ("wireframes", "wireframe"), ("mockups", "mockup"), ("implemented", "implemented screenshot")):
        d = UI / uc / kind
        files = sorted(p for p in d.glob("*") if p.suffix.lower() in (".png", ".jpg", ".jpeg", ".pdf")) if d.exists() else []
        if kind == "sketch" and not files:
            out.append("| `sketch/` | sketch (owner) | OWNER-PENDING: no sketch photo exists yet |")
        for p in files:
            out.append(f"| `{kind}/{p.name}` | {label} | {created(p)} |")
    (UI / uc / "trace.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(uc, f"{len(smap)} rows, view check failures: {failed}")
    return failed


if __name__ == "__main__":
    sys.exit(sum(build(u) for u in sys.argv[1:]) > 0)
